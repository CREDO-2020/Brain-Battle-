-- Brain Battle profile and leaderboard setup.
-- Run after supabase/schema.sql in a fresh project.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Brain Battler',
  created_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
drop policy if exists "Profiles are publicly readable" on public.profiles;
create policy "Profiles are publicly readable" on public.profiles for select to anon, authenticated using (true);
drop policy if exists "Players can update their own profile" on public.profiles;
create policy "Players can update their own profile" on public.profiles for update to authenticated
  using ((select auth.uid()) = id) with check ((select auth.uid()) = id);
grant select on public.profiles to anon, authenticated;
grant update on public.profiles to authenticated;

create or replace function public.handle_new_brain_battle_user()
returns trigger language plpgsql security definer set search_path = ''
as $$
begin
  insert into public.profiles (id, display_name)
  values (new.id, coalesce(nullif(trim(new.raw_user_meta_data ->> 'display_name'), ''), split_part(coalesce(new.email, 'player'), '@', 1)))
  on conflict (id) do nothing;
  return new;
end;
$$;
revoke execute on function public.handle_new_brain_battle_user() from public, anon, authenticated;
drop trigger if exists on_brain_battle_user_created on auth.users;
create trigger on_brain_battle_user_created after insert on auth.users for each row execute procedure public.handle_new_brain_battle_user();

-- Public ranking data is stored separately from private quiz attempts.
create table if not exists public.leaderboard (
  id bigint generated by default as identity primary key,
  display_name text not null,
  score integer not null,
  category text not null,
  correct_answers integer not null,
  total_questions integer not null,
  created_at timestamptz not null default now()
);
alter table public.leaderboard enable row level security;
drop policy if exists "Leaderboard is publicly readable" on public.leaderboard;
create policy "Leaderboard is publicly readable" on public.leaderboard for select to anon, authenticated using (true);
grant select on public.leaderboard to anon, authenticated;

create or replace function public.publish_brain_battle_score()
returns trigger language plpgsql security definer set search_path = ''
as $$
declare player_name text;
begin
  select p.display_name into player_name from public.profiles p where p.id = new.user_id;
  insert into public.leaderboard (display_name, score, category, correct_answers, total_questions, created_at)
  values (coalesce(nullif(trim(player_name), ''), 'Brain Battler'), new.score, new.category, new.correct_answers, new.total_questions, new.created_at);
  return new;
end;
$$;
revoke execute on function public.publish_brain_battle_score() from public, anon, authenticated;
drop trigger if exists on_brain_battle_attempt_created on public.quiz_attempts;
create trigger on_brain_battle_attempt_created after insert on public.quiz_attempts for each row execute procedure public.publish_brain_battle_score();
