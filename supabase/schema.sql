-- Brain Battle database schema
-- Run in the Supabase SQL Editor for a fresh project.

create table if not exists public.questions (
  id bigint generated by default as identity primary key,
  category text not null,
  question text not null,
  options jsonb not null,
  correct_index integer not null,
  explanation text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);

create table if not exists public.quiz_attempts (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null,
  score integer not null default 0,
  total_questions integer not null,
  correct_answers integer not null,
  created_at timestamptz not null default now()
);

alter table public.questions enable row level security;
alter table public.quiz_attempts enable row level security;

grant select on public.questions to anon, authenticated;
grant select, insert on public.quiz_attempts to authenticated;

drop policy if exists "Read active quiz questions" on public.questions;
create policy "Read active quiz questions" on public.questions
  for select using (is_active = true);

drop policy if exists "Read own quiz attempts" on public.quiz_attempts;
create policy "Read own quiz attempts" on public.quiz_attempts
  for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists "Insert own quiz attempts" on public.quiz_attempts;
create policy "Insert own quiz attempts" on public.quiz_attempts
  for insert to authenticated with check ((select auth.uid()) = user_id);

insert into public.questions(category, question, options, correct_index, explanation)
select seed.category, seed.question, seed.options::jsonb, seed.correct_index, seed.explanation
from (values
  ('Science', 'Which planet is known as the Red Planet?', '["Venus","Mars","Jupiter","Mercury"]', 1, 'Mars looks reddish because iron minerals in its soil have oxidized.'),
  ('Technology', 'What does CPU stand for?', '["Computer Power Unit","Central Processing Unit","Core Program Utility","Central Performance User"]', 1, 'The CPU executes instructions and performs calculations.'),
  ('General Knowledge', 'What is the largest ocean on Earth?', '["Atlantic Ocean","Indian Ocean","Arctic Ocean","Pacific Ocean"]', 3, 'The Pacific Ocean is the largest and deepest ocean.'),
  ('History', 'The ancient pyramids of Giza are in which country?', '["Mexico","Greece","Egypt","Sudan"]', 2, 'The Giza pyramid complex is in Egypt.'),
  ('Sports', 'How many players from one football team are on the pitch at kickoff?', '["9","10","11","12"]', 2, 'A standard football team fields eleven players, including the goalkeeper.')
) as seed(category, question, options, correct_index, explanation)
where not exists (
  select 1 from public.questions existing where existing.question = seed.question
);
